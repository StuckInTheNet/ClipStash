export function applyTheme(theme: Theme) {
  const root = document.documentElement;
  const c = theme.colors;
  root.style.setProperty("--color-surface", c.surface);
  root.style.setProperty("--color-surface-raised", c.surfaceRaised);
  root.style.setProperty("--color-surface-hover", c.surfaceHover);
  root.style.setProperty("--color-border-subtle", c.borderSubtle);
  root.style.setProperty("--color-border-hover", c.borderHover);
  root.style.setProperty("--color-accent", c.accent);
  root.style.setProperty("--color-accent-dim", c.accentDim);
  root.style.setProperty("--color-accent-hover", c.accentHover);
  root.style.setProperty("--color-text-primary", c.textPrimary);
  root.style.setProperty("--color-text-secondary", c.textSecondary);
  root.style.setProperty("--color-text-muted", c.textMuted);
  root.style.setProperty("--color-success", c.success);
  root.style.setProperty("--color-danger", c.danger);
  root.style.setProperty("--color-warning", c.warning);
  root.style.setProperty("--color-code-bg", c.codeBg);
  root.style.setProperty("--color-code-text", c.codeText);

  // Update body background for light themes
  document.body.style.background = c.surface;
  document.body.style.color = c.textPrimary;
}

export function getSavedThemeId(): string {
  return localStorage.getItem("clipstash-theme") || "midnight";
}

export function saveThemeId(id: string) {
  localStorage.setItem("clipstash-theme", id);
}

export function getThemeById(id: string): Theme {
  return themes.find((t) => t.id === id) || themes[0];
}
